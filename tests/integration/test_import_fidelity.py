"""EVAL-002: every fixture's nodes are accounted for; a silent loss is caught."""

from __future__ import annotations

import json
import shutil
from pathlib import Path

import pytest

from knowledge_engine.evaluation.import_fidelity import (
    census,
    evaluate_export,
    evaluate_fixtures,
    to_markdown,
    verdict,
)

FIXTURES = Path(__file__).resolve().parents[1] / "fixtures" / "chatgpt"


def test_every_fixture_is_accounted_for_or_warned(tmp_path: Path) -> None:
    report = evaluate_fixtures(FIXTURES, tmp_path)
    assert len(report.exports) == len([p for p in FIXTURES.iterdir() if (p / "export").exists()])
    assert report.passed
    assert all(e.dropped_nodes == 0 for e in report.exports)
    assert all(e.inactive_kept == e.inactive_nodes for e in report.exports)  # branches kept
    by_name = {e.name: e for e in report.exports}
    assert by_name["branches_regen"].inactive_nodes == 2
    assert by_name["asset_problems"].missing_assets > 0
    assert by_name["asset_problems"].verdict == "warned"  # missing images are said, not hidden
    assert by_name["export_zip"].source_nodes == by_name["export_single"].source_nodes
    text = to_markdown(report)
    assert "**PASS**" in text and "| branches_regen | official |" in text


def test_a_conversation_the_importer_never_reads_is_a_silent_drop(tmp_path: Path) -> None:
    # Failing-case reproduction: a second JSON file of conversations next to
    # conversations.json is not read by the official adapter, and nothing says so.
    export = tmp_path / "export"
    export.mkdir()
    shutil.copy(FIXTURES / "similar_unrelated" / "export" / "conversations.json", export)
    stray = json.loads((FIXTURES / "branches_edit" / "export" / "conversations.json").read_text())
    (export / "stray.json").write_text(json.dumps(stray), encoding="utf-8")
    result = evaluate_export(export, tmp_path / "scratch", name="stray", layout="official")
    assert result.source_conversations == 3 and result.stored_conversations == 2
    assert result.dropped_nodes == len(census(export).nodes[stray[0]["id"]])
    # Was "silent_drop"; IMP-007 (#237) makes the importer warn about the
    # stray file, so the drop is now admitted in the report.
    assert result.verdict == "warned"


@pytest.mark.parametrize(
    ("dropped", "warnings", "reconciled", "missing", "expected"),
    [
        (0, {}, True, 0, "ok"),
        (0, {}, True, 2, "warned"),
        (3, {"conversation_failed": 1}, True, 0, "warned"),
        (3, {}, False, 0, "warned"),
        (3, {}, True, 0, "silent_drop"),
    ],
)
def test_verdict(
    dropped: int, warnings: dict[str, int], reconciled: bool, missing: int, expected: str
) -> None:
    assert verdict(dropped, warnings, reconciled, missing) == expected


def test_cli_eval_fidelity(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    from knowledge_engine.cli.main import main

    monkeypatch.setenv("KE_WORKSPACE_ROOT", str(tmp_path / "ws"))
    out = tmp_path / "FIDELITY.md"
    assert main(["--json", "eval", "fidelity", "--fixtures", str(FIXTURES), "--out", str(out)]) == 0
    data = json.loads(capsys.readouterr().out)["data"]
    assert data["passed"] and "silent_drop" not in data["verdicts"]
    assert out.read_text(encoding="utf-8").startswith("<!-- Generated by `ke eval fidelity`")
    assert not (tmp_path / "ws").exists()  # scratch workspaces only, never yours
    assert main(["--json", "eval", "fidelity", "--fixtures", str(tmp_path / "nope")]) == 2

"""EVAL-005: no later statement is wrongly recorded as replacing an earlier decision."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from knowledge_engine.evaluation.temporal_bench import (
    CASES,
    run_benchmark,
    run_pairs,
    to_dict,
    to_markdown,
)
from knowledge_engine.reconciliation.supersession import Outcome

FIXTURES = Path(__file__).resolve().parents[1] / "fixtures" / "chatgpt"


def test_no_false_supersession_in_the_curated_pairs() -> None:
    results = {r.case_id: r for r in run_pairs()}
    assert len(results) == len(CASES)
    assert [r.case_id for r in results.values() if r.false_supersession] == []
    for r in results.values():
        if r.category == "hypothetical":
            assert r.got is Outcome.REVIEW_REQUIRED and "hypothetical" in r.failed_tests
    # Another part of the same project, with a shared word and a firm "instead":
    # the named target decides, and an unnamed one goes to a person.
    assert results["a01"].got is Outcome.UNRELATED
    assert results["a03"].got is Outcome.UNRELATED
    assert results["a02"].got is Outcome.REVIEW_REQUIRED
    # The price of that safety: replacements that don't say what they replace
    # are sent to review rather than recorded. Reported, never hidden.
    missed = [
        r.case_id
        for r in results.values()
        if r.expected is Outcome.SUPERSEDES and r.got is not Outcome.SUPERSEDES
    ]
    assert missed == ["t02", "t04"]
    assert all(results[c].got is Outcome.REVIEW_REQUIRED for c in missed)


def test_history_is_kept_end_to_end(tmp_path: Path) -> None:
    report = run_benchmark(FIXTURES / "engine_switch" / "export", tmp_path)
    assert report.pipeline.passed
    assert report.passed
    data = to_dict(report)
    assert data["false_supersessions"] == [] and data["missed_supersessions"] == ["t02", "t04"]
    assert "**PASS**" in to_markdown(report)


def test_cli_eval_temporal(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    from knowledge_engine.cli.main import main

    monkeypatch.setenv("KE_WORKSPACE_ROOT", str(tmp_path / "ws"))
    out = tmp_path / "TEMPORAL.md"
    assert main(["--json", "eval", "temporal", "--fixtures", str(FIXTURES), "--out", str(out)]) == 0
    data = json.loads(capsys.readouterr().out)["data"]
    assert data["passed"] and data["false_supersessions"] == []
    assert out.read_text(encoding="utf-8").startswith("<!-- Generated by `ke eval temporal`")
    assert not (tmp_path / "ws").exists()
